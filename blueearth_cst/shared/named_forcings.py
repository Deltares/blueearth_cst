"""Named historical forcing recipes, their default and their native file layout.

A project either declares one legacy recipe (``climate.forcing``) or a named map
(``climate.forcings`` plus ``climate.default_forcing``). Composition resolves the
active named recipe into the legacy internal representation, so consumers that
read ``climate.selected``/``climate.forcing`` stay unchanged.

Kept out of ``forcing_recipe.py`` on purpose: that module is in WF3's hashed
import closure, and the named map never reaches generated bytes.
"""

from __future__ import annotations

import re
from collections.abc import Mapping
from dataclasses import dataclass

FORCING_ID = re.compile(r"[a-z][a-z0-9_]{0,31}")
RESERVED_IDS = frozenset({"default"})
#: Public keys of the named form; composition removes them before legacy resolution.
NAMED_KEYS = ("forcings", "default_forcing")


def declares_named(climate: Mapping[str, object]) -> bool:
    """Whether the climate section uses the named-recipe form."""
    return any(key in climate for key in NAMED_KEYS)


def _forcing_id(value: object, field: str) -> str:
    if not isinstance(value, str) or not FORCING_ID.fullmatch(value):
        raise ValueError(f"{field} must match [a-z][a-z0-9_]{{0,31}}, got {value!r}")
    if value in RESERVED_IDS:
        raise ValueError(f"{field}: {value!r} is reserved for the single-recipe layout")
    return value


def named_recipes(climate: Mapping[str, object]) -> tuple[dict[str, dict], str]:
    """Validate the named map's shape and return ``(recipes, default_id)``.

    Recipe bodies are the public ``climate.forcing`` mapping; their scientific
    content is validated later through the ordinary legacy resolver.
    """
    if not ("forcings" in climate and "default_forcing" in climate):
        raise ValueError(
            "climate.forcings and climate.default_forcing must be declared together"
        )
    for legacy in ("forcing", "selected"):
        if legacy in climate:
            raise ValueError(
                f"climate.forcings replaces climate.{legacy}; declare only one form"
            )
    raw = climate["forcings"]
    if not isinstance(raw, Mapping) or not raw:
        raise ValueError(
            "climate.forcings must be a non-empty mapping of named recipes"
        )
    recipes: dict[str, dict] = {}
    for key, body in raw.items():
        _forcing_id(key, "climate.forcings key")
        if not isinstance(body, Mapping):
            raise ValueError(f"climate.forcings.{key} must be a forcing mapping")
        recipes[key] = dict(body)
    default = _forcing_id(climate["default_forcing"], "climate.default_forcing")
    if default not in recipes:
        raise ValueError(
            f"climate.default_forcing {default!r} is not one of climate.forcings "
            f"{sorted(recipes)!r}"
        )
    return recipes, default


def legacy_view(climate: Mapping[str, object], forcing_id: str) -> dict[str, object]:
    """The single-recipe public climate section equivalent to one named recipe."""
    recipes, _ = named_recipes(climate)
    view = {key: value for key, value in climate.items() if key not in NAMED_KEYS}
    view["forcing"] = recipes[forcing_id]
    return view


def resolve_selection(
    climate: Mapping[str, object], requested: object, field: str
) -> str | None:
    """Resolve ``default`` or an explicit recipe ID; ``None`` in legacy layout."""
    if requested is None:
        requested = "default"
    if not isinstance(requested, str):
        raise ValueError(f"{field} must be default or a climate.forcings name")
    if not declares_named(climate):
        if requested != "default":
            raise ValueError(
                f"{field}: {requested!r} requires climate.forcings; "
                "a single-recipe project only offers default"
            )
        return None
    recipes, default = named_recipes(climate)
    if requested == "default":
        return default
    if requested not in recipes:
        raise ValueError(
            f"{field}: unknown forcing {requested!r}; choose default or one of "
            f"{sorted(recipes)!r}"
        )
    return requested


def historical_forcing_ids(
    climate: Mapping[str, object], build_model: Mapping[str, object]
) -> tuple[str, ...] | None:
    """WF1's requested recipe IDs; ``None`` selects the single-recipe layout."""
    raw = build_model.get("historical_forcings")
    if not declares_named(climate):
        if raw is not None:
            raise ValueError(
                "build_model.historical_forcings requires climate.forcings"
            )
        return None
    recipes, default = named_recipes(climate)
    if raw is None:
        return (default,)
    if not isinstance(raw, list) or not raw:
        raise ValueError("build_model.historical_forcings must be a non-empty list")
    if len(set(map(str, raw))) != len(raw):
        raise ValueError("build_model.historical_forcings contains duplicates")
    for item in raw:
        if item not in recipes:
            raise ValueError(
                f"build_model.historical_forcings: unknown forcing {item!r}; "
                f"declared: {sorted(recipes)!r}"
            )
    return tuple(raw)


def composed_forcing_ids(
    climate: Mapping[str, object], build_model: Mapping[str, object]
) -> tuple[str, ...] | None:
    """WF1's recipe IDs from an already composed (validated) configuration."""
    if "forcing_id" not in climate:
        return None
    return tuple(build_model.get("historical_forcings") or [climate["default_forcing"]])


def retained_run_names(
    name: str | None, forcing_ids: tuple[str, ...] | None
) -> dict[str | None, str | None]:
    """Map each executed recipe to its retained run name.

    Legacy layout keeps the authored name. Named layout derives ``<name>_<id>``;
    two or more recipes require a name so the comparison reads retained runs.
    """
    if forcing_ids is None:
        return {None: name}
    if name is None:
        if len(forcing_ids) > 1:
            raise ValueError(
                "build_model.historical_run.name is required when "
                "historical_forcings lists two or more recipes"
            )
        return {forcing_ids[0]: None}
    from blueearth_cst.model.historical_runs import historical_run_name

    return {
        forcing_id: historical_run_name({"name": f"{name}_{forcing_id}"})
        for forcing_id in forcing_ids
    }


@dataclass(frozen=True)
class HistoricalLayout:
    """Model-root-relative locations of one recipe's native historical run."""

    forcing_id: str | None

    @property
    def forcing(self) -> str:
        if self.forcing_id is None:
            return "forcing/inmaps_historical.nc"
        return f"forcing/{self.forcing_id}/inmaps_historical.nc"

    @property
    def toml(self) -> str:
        return (
            "wflow_sbm.toml"
            if self.forcing_id is None
            else f"wflow_sbm_{self.forcing_id}.toml"
        )

    @property
    def run_dir(self) -> str:
        return "run_default" if self.forcing_id is None else f"run_{self.forcing_id}"

    @property
    def config_dir(self) -> str:
        return "config" if self.forcing_id is None else f"config/{self.forcing_id}"

    @property
    def evaluation_dir(self) -> str:
        return "evaluation" if self.forcing_id is None else f"evaluation/{self.forcing_id}"

    @property
    def forcing_plots_dir(self) -> str:
        if self.forcing_id is None:
            return "forcing/plots"
        return f"forcing/{self.forcing_id}/plots"

    @property
    def end_state(self) -> str:
        return f"{self.run_dir}/outstate/outstates.nc"

    @property
    def discharge_csv(self) -> str:
        return f"{self.run_dir}/output.csv"
