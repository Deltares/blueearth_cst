"""Write ``config/catalogs/deltares_data_staged.yml`` from the vendored P: catalog.

``stage_data.py`` mirrors a bbox-clipped subset of ``p:/wflow_global/hydromt``
onto ``C:/data/wflow_global/hydromt`` with the same relative paths. The overlay
written here holds only the vendored entries whose files the staging config
copies, verbatim, under roots that try the local mirror first and fall back to
the P: drive. Listed after ``deltares_data_pdrive.yml``, it makes staged datasets
read locally when the mirror exists; everything else still reads from P:.

Run after changing ``dev/scripts/stage_data.yml`` or the vendored catalog::

    python dev/scripts/write_staged_catalog.py

``tests/test_staged_catalog.py`` fails when the committed overlay is stale.
"""

from __future__ import annotations

import fnmatch
from pathlib import Path

import yaml

REPO = Path(__file__).resolve().parents[2]
VENDORED = REPO / "config/catalogs/deltares_data_pdrive.yml"
STAGING = REPO / "dev/scripts/stage_data.yml"
OUTPUT = REPO / "config/catalogs/deltares_data_staged.yml"
LOCAL_ROOT = "C:/data/wflow_global/hydromt"

#: Files a glob-type staged dataset copies, by type (stage_data.py defaults).
DEFAULT_PATTERNS = {"raster_glob": "*.tif", "netcdf_glob": "*.nc"}

HEADER = """\
# GENERATED by dev/scripts/write_staged_catalog.py -- do not hand-edit.
#
# The entries of deltares_data_pdrive.yml whose files dev/scripts/stage_data.yml
# mirrors locally, verbatim, with the local mirror as the first root and the
# P: drive as the fallback (hydromt takes the first root that exists). List it
# AFTER deltares_data_pdrive.yml: later catalogs override same-named entries.
"""


def _staged(entry_uri: str, datasets: list[dict]) -> bool:
    uri = entry_uri.replace("\\", "/")
    for dataset in datasets:
        path = dataset["path"].rstrip("/")
        if uri == path:
            return True
        if uri.startswith(path + "/"):
            pattern = dataset.get("pattern") or DEFAULT_PATTERNS.get(dataset["type"])
            if pattern is None or fnmatch.fnmatch(uri[len(path) + 1 :], pattern):
                return True
    return False


def staged_catalog() -> str:
    vendored = yaml.safe_load(VENDORED.read_text(encoding="utf-8"))
    datasets = yaml.safe_load(STAGING.read_text(encoding="utf-8"))["datasets"]
    meta = dict(vendored["meta"])
    meta["roots"] = [LOCAL_ROOT, *meta["roots"]]
    entries = {
        name: entry
        for name, entry in vendored.items()
        if name != "meta"
        and isinstance(entry, dict)
        and _staged(entry.get("uri") or entry.get("path") or "", datasets)
    }
    body = yaml.safe_dump({"meta": meta, **entries}, sort_keys=False)
    return HEADER + "\n" + body


if __name__ == "__main__":
    OUTPUT.write_text(staged_catalog(), encoding="utf-8", newline="\n")
    print(f"wrote {OUTPUT.relative_to(REPO)}")
